// Moves ts-proto's per-file `interface MessageFns<T>` into one exported module.
//
// With outputIndex=true, ts-proto keeps MessageFns unexported (otherwise the `export *`
// index files would export conflicting names). The nice-grpc service definitions reference
// message types from other files, so their inferred types need MessageFns, and tsc cannot
// emit declarations for an unexported interface (TS4023). The interface is identical in
// every file, so it is written once to src/shared/MessageFns.ts and imported everywhere.
//
// Usage: node scripts/share-message-fns.mjs <src dir>
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";

const srcDir = process.argv[2];
const sharedFile = join(srcDir, "shared", "MessageFns.ts");
const blockRe = /^interface MessageFns<T> \{\n[\s\S]*?\n\}\n/m;
const deepPartialRe = /^type Builtin = [^\n]*\n\ntype DeepPartial<T> = [\s\S]*?;\n/m;

const files = readdirSync(srcDir, { recursive: true })
  .map((f) => join(srcDir, f))
  .filter((f) => f.endsWith(".ts") && !f.startsWith(join(srcDir, "lib") + sep) && !f.startsWith(join(srcDir, "shared") + sep));

let block;
let deepPartial;
let count = 0;
for (const file of files) {
  const text = readFileSync(file, "utf8");
  const m = text.match(blockRe);
  if (!m) continue;
  if (block === undefined) {
    block = m[0];
    deepPartial = text.match(deepPartialRe)?.[0];
    if (!deepPartial) throw new Error(`${file}: MessageFns found but no DeepPartial`);
  } else if (m[0] !== block) {
    throw new Error(`${file}: MessageFns differs from the other files, update ${import.meta.url}`);
  }
  let rel = relative(dirname(file), sharedFile).split(sep).join("/").replace(/\.ts$/, ".js");
  if (!rel.startsWith(".")) rel = "./" + rel;
  const out = text.replace(blockRe, "").replace(/^(\/\* eslint-disable \*\/\n)/m, `$1import type { MessageFns } from "${rel}";\n`);
  if (out === text.replace(blockRe, "")) throw new Error(`${file}: no eslint-disable header to insert the import after`);
  writeFileSync(file, out);
  count++;
}

if (block === undefined) throw new Error("no MessageFns found, did the ts-proto output change?");

mkdirSync(dirname(sharedFile), { recursive: true });
writeFileSync(
  sharedFile,
  `// Generated by scripts/share-message-fns.mjs from the ts-proto output. DO NOT EDIT.
import type { BinaryReader, BinaryWriter } from "@bufbuild/protobuf/wire";

${deepPartial}
export ${block}`,
);
console.log(`share-message-fns: ${count} files now import MessageFns from ${sharedFile}`);
